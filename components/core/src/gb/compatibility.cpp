// Pan Docs, Power Up Sequence, Compatibility palettes: a cartridge whose
// licensee is not Nintendo takes the default palettes too.
std::array<uint16_t, 12> compatibility_palettes(std::span<const uint8_t> rom) {
    unsigned palette = kAssignments[0].palette;
    if (nintendo_licensee(rom)) {
        const uint8_t checksum = title_checksum(rom);
        const char letter = static_cast<char>(rom[0x137]);
        for (const auto& a : kAssignments)
            if (a.checksum == checksum && (!a.letter || a.letter == letter)) { palette = a.palette; break; }
    }
    return kPalettes[palette];
}
