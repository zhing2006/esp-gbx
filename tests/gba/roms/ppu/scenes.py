"""Scenes of the GBX PPU test ROMs.

Each function below builds one scene; tools/gba_test_roms.py turns it into a
blob for player.c, and model.py computes the frame it should show. The
docstring of each scene lists the GBATEK sections it covers. Every scene shows
the same picture in every frame, and register changes within a frame happen
only in H-Blank (see player.c), so a line-based PPU can match the frame
exactly.

Tile pixels are generated by formulas instead of art so that every tile,
flip and palette bank differs visibly. Most tiles keep their last row and
column transparent, so lower layers show through a grid.
"""

import struct

from model import OBJ_SIZES, Regs

LINES = 161
BY_DMA, BY_IRQ = 0, 1
MAGIC = 0x4E435347  # 'GSCN'


def rgb(r, g, b):
    return (r & 31) | ((g & 31) << 5) | ((b & 31) << 10)


def color(bank, index):
    """A distinct color for each palette bank and index."""
    return rgb(index * 5 + bank * 3 + 4, index * 11 + bank * 7 + 2, index * 17 + bank * 13 + 9)


# Channel levels for scenes with color effects. Alpha blending with even
# coefficients and brightness decrease with an even EVY give whole results
# for multiples of 8; brightness increase with an even EVY for 31 minus
# multiples of 8 (see model.blend()).
LEVELS_8 = (0, 8, 16, 24)
LEVELS_UP = (7, 15, 23, 31)


def quantize(value, levels):
    out = 0
    for shift in (0, 5, 10):
        c = (value >> shift) & 31
        out |= min(levels, key=lambda v: abs(v - c)) << shift
    return out


def glyph4(k):
    """8x8 4bpp tile: transparent right column and bottom row, a marker in the
    top-left corner so that flips show."""
    rows = []
    for y in range(8):
        row = []
        for x in range(8):
            if x == 7 or y == 7:
                row.append(0)
            elif x < 2 and y < 2:
                row.append(15)
            elif x < 3 and y == 2:
                row.append(14)
            else:
                row.append(1 + (x + 2 * y + 3 * k) % 13)
        rows.append(row)
    return rows


def glyph8(k):
    rows = []
    for y in range(8):
        row = []
        for x in range(8):
            if x == 7 or y == 7:
                row.append(0)
            elif x < 2 and y < 2:
                row.append(255)
            elif x < 3 and y == 2:
                row.append(254)
            else:
                row.append(1 + (x * 7 + y * 13 + k * 29) % 250)
        rows.append(row)
    return rows


def solid4(index):
    return [[index] * 8 for _ in range(8)]


class Scene:
    def __init__(self, name, doc):
        self.name = name
        self.doc = doc
        self.vram = bytearray(0x18000)
        self.pram = bytearray(0x400)
        self.oam = bytearray(0x400)
        self.io = {}
        self.groups = []
        self.dispcnt = 0
        for i in range(128):
            struct.pack_into('<H', self.oam, i * 8, 0x0200)  # OBJ disabled

    # Memory helpers

    def bg_color(self, index, value):
        struct.pack_into('<H', self.pram, index * 2, value)

    def obj_color(self, index, value):
        struct.pack_into('<H', self.pram, 0x200 + index * 2, value)

    def bg_palettes(self, banks=16):
        for bank in range(banks):
            for i in range(1, 16):
                self.bg_color(bank * 16 + i, color(bank, i))

    def bg_palette256(self):
        for i in range(1, 256):
            self.bg_color(i, color(i >> 4, i & 15) ^ (i * 0x0421 & 0x7FFF))

    def obj_palettes(self, banks=16):
        for bank in range(banks):
            for i in range(1, 16):
                self.obj_color(bank * 16 + i, color(bank + 5, i + 1))

    def quantize_bank(self, bank, levels, obj=False, first=1):
        """Moves colors first..15 of a 16-color bank to the given levels,
        keeping them distinct where the levels allow."""
        base = 0x200 if obj else 0
        for i in range(first, 16):
            addr = base + (bank * 16 + i) * 2
            value = struct.unpack_from('<H', self.pram, addr)[0]
            struct.pack_into('<H', self.pram, addr, quantize(value, levels))

    def obj_palette256(self):
        for i in range(1, 256):
            self.obj_color(i, color(i >> 4, i & 15) ^ (i * 0x1084 & 0x7FFF))

    def tile4(self, base, index, rows):
        for y, row in enumerate(rows):
            for x in range(0, 8, 2):
                self.vram[base + index * 32 + y * 4 + x // 2] = row[x] | (row[x + 1] << 4)

    def tile8(self, base, index, rows):
        for y, row in enumerate(rows):
            for x in range(8):
                self.vram[base + index * 64 + y * 8 + x] = row[x]

    def obj_tile8(self, name, rows):
        """256-color OBJ tile; OBJ tile numbers count 32-byte units (GBATEK
        "LCD OBJ - OAM Attributes", OBJ Tile Number)."""
        for y, row in enumerate(rows):
            for x in range(8):
                self.vram[0x10000 + (name & 0x3FF) * 32 + y * 8 + x] = row[x]

    def text_entry(self, screen_block, size, tx, ty, tile, hflip=False, vflip=False, pal=0):
        """Map entry of a text BG at tile coordinates (tx, ty) of the whole
        BG (GBATEK "LCD VRAM BG Screen Data Format (BG Map)")."""
        block = (0, tx // 32, ty // 32, tx // 32 + 2 * (ty // 32))[size]
        addr = screen_block * 0x800 + block * 0x800 + (ty % 32) * 64 + (tx % 32) * 2
        struct.pack_into('<H', self.vram, addr, tile | (hflip << 10) | (vflip << 11) | (pal << 12))

    def affine_entry(self, screen_block, size_tiles, tx, ty, tile):
        self.vram[screen_block * 0x800 + ty * size_tiles + tx] = tile

    def obj(self, i, x, y, shape, size, tile, prio=0, pal=0, color256=False, hflip=False,
            vflip=False, affine=None, double=False, mode=0, mosaic=False):
        a0 = (y & 0xFF) | (mode << 10) | (mosaic << 12) | (color256 << 13) | (shape << 14)
        a1 = (x & 0x1FF) | (size << 14)
        if affine is None:
            a1 |= (hflip << 12) | (vflip << 13)
        else:
            a0 |= 0x100 | (double << 9)
            a1 |= affine << 9
        a2 = tile | (prio << 10) | (pal << 12)
        struct.pack_into('<HHH', self.oam, i * 8, a0, a1, a2)

    def obj_affine(self, group, pa, pb, pc, pd):
        for k, v in enumerate((pa, pb, pc, pd)):
            struct.pack_into('<h', self.oam, group * 32 + 6 + 8 * k, v)

    def reg(self, addr, value, width=2):
        self.io[addr] = (value & (0xFFFF if width == 2 else 0xFFFFFFFF), width)

    def per_line(self, addr, width, values, mode=BY_DMA, channel=0):
        """values(line) gives the register values for lines 0..160; line L is
        written in the H-Blank of line L-1 (line 0 in V-Blank)."""
        table = [list(values(line)) for line in range(LINES)]
        self.groups.append((addr, width, len(table[0]), mode, channel, table))

    # Model support

    def line_values(self):
        out = []
        for line in range(160):
            writes = []
            for addr, width, units, mode, channel, table in self.groups:
                for i, v in enumerate(table[line]):
                    writes.append((addr + i * width, width, v))
            out.append(writes)
        return out

    def written_by_lines(self):
        regs = set()
        for addr, width, units, mode, channel, table in self.groups:
            for i in range(units):
                regs.add(addr + i * width)
                if width == 4:
                    regs.add(addr + i * width + 2)
        return regs

    def reference_writes(self):
        written = self.written_by_lines()
        out = set()
        for n in (2, 3):
            base = 0x04000028 + 0x10 * (n - 2)
            if written & {base, base + 2, base + 4, base + 6}:
                out.update((n, line) for line in range(1, 160))
        return out

    def check_bg_tile(self, addr):
        if addr >= 0x10000:
            raise ValueError(f'{self.name}: BG tile data at {addr:#x} is outside BG VRAM')

    def check(self):
        written = self.written_by_lines()
        values = self.line_values()
        for n in (2, 3):
            base = 0x04000020 + 0x10 * (n - 2)
            pb_pd = (base + 2, base + 6)
            ref = {base + 8, base + 10, base + 12, base + 14}
            seen = {a: set() for a in pb_pd}
            for line in range(160):
                regs = Regs(self.io)
                for addr, width, v in values[line]:
                    regs.write(addr, v, width)
                for a in pb_pd:
                    seen[a].add(regs[a - 0x04000000])
            if any(len(v) > 1 for v in seen.values()):
                raise ValueError(f'{self.name}: BG{n} PB/PD change within the frame')
            if written & ref and set().union(*seen.values()) - {0}:
                raise ValueError(f'{self.name}: BG{n} reference point written per line with PB/PD not 0')
        self.check_objs()

    def check_objs(self):
        boxes = []
        mosaic = self.io.get(0x0400004C, (0, 2))[0]
        omh, omv = ((mosaic >> 8) & 15) + 1, ((mosaic >> 12) & 15) + 1
        for i in range(128):
            a0, a1, a2 = struct.unpack_from('<HHH', self.oam, i * 8)
            affine = a0 & 0x100
            if not affine and a0 & 0x200:
                continue
            w, h = OBJ_SIZES[(a0 >> 14) & 3][a1 >> 14]
            if affine and a0 & 0x200:
                w, h = w * 2, h * 2
            x, y = a1 & 0x1FF, a0 & 0xFF
            if a0 & 0x1000 and (x % omh or y % omv):
                raise ValueError(f'{self.name}: mosaic OBJ {i} is not on the mosaic grid')
            if (a0 >> 10) & 3 == 2:
                continue
            cols = {(x + k) & 0x1FF for k in range(w)}
            rows = {(y + k) & 0xFF for k in range(h)}
            for j, (c, r, prio) in enumerate(boxes):
                if c & cols and r & rows and prio > (a2 >> 10) & 3:
                    raise ValueError(f'{self.name}: OBJ {i} overlaps OBJ {j} with a higher priority')
            boxes.append((cols, rows, (a2 >> 10) & 3))

    def blob(self):
        header = struct.Struct('<10I')
        io = b''.join(struct.pack('<III', a, v, w) for a, (v, w) in self.io.items())
        tables = []
        offset = header.size + 0x18000 + 0x800 + len(io) + 24 * len(self.groups)
        group_data = b''
        for addr, width, units, mode, channel, table in self.groups:
            fmt = '<' + ('I' if width == 4 else 'H') * units
            data = b''.join(struct.pack(fmt, *row) for row in table)
            data += bytes(-len(data) % 4)
            group_data += struct.pack('<6I', addr, width, units, mode, channel, offset)
            tables.append(data)
            offset += len(data)
        vram_off = header.size
        pram_off = vram_off + 0x18000
        oam_off = pram_off + 0x400
        io_off = oam_off + 0x400
        group_off = io_off + len(io)
        head = header.pack(MAGIC, vram_off, 0x18000, pram_off, oam_off, len(self.io), io_off,
                           len(self.groups), group_off, self.dispcnt)
        return head + bytes(self.vram) + bytes(self.pram) + bytes(self.oam) + io + group_data + b''.join(tables)


# Register addresses (GBATEK "GBA I/O Map")
DISPCNT = 0x04000000
BGCNT = [0x04000008 + 2 * n for n in range(4)]
BGHOFS = [0x04000010 + 4 * n for n in range(4)]
BGVOFS = [0x04000012 + 4 * n for n in range(4)]
BGPA = {2: 0x04000020, 3: 0x04000030}
BGPB = {2: 0x04000022, 3: 0x04000032}
BGPC = {2: 0x04000024, 3: 0x04000034}
BGPD = {2: 0x04000026, 3: 0x04000036}
BGX = {2: 0x04000028, 3: 0x04000038}
BGY = {2: 0x0400002C, 3: 0x0400003C}
WIN0H, WIN1H, WIN0V, WIN1V = 0x04000040, 0x04000042, 0x04000044, 0x04000046
WININ, WINOUT, MOSAIC = 0x04000048, 0x0400004A, 0x0400004C
BLDCNT, BLDALPHA, BLDY = 0x04000050, 0x04000052, 0x04000054


def bgcnt(prio=0, char=0, mosaic=False, color256=False, screen=0, wrap=False, size=0):
    return prio | (char << 2) | (mosaic << 6) | (color256 << 7) | (screen << 8) | (wrap << 13) | (size << 14)


def affine(scene, n, pa, pb, pc, pd, x, y):
    scene.reg(BGPA[n], pa)
    scene.reg(BGPB[n], pb)
    scene.reg(BGPC[n], pc)
    scene.reg(BGPD[n], pd)
    scene.reg(BGX[n], x, 4)
    scene.reg(BGY[n], y, 4)


def text_layer(scene, n, size, screen, tiles, char=0, color256=False, prio=0, pattern=None):
    """Fills BG n's whole map. pattern(tx, ty) returns (tile, hflip, vflip,
    pal) or None for an empty (transparent) entry."""
    width, height = (32, 64, 32, 64)[size], (32, 32, 64, 64)[size]
    for ty in range(height):
        for tx in range(width):
            entry = pattern(tx, ty)
            if entry is not None:
                tile, hf, vf, pal = entry
                scene.text_entry(screen, size, tx, ty, tile, hf, vf, pal)
    scene.reg(BGCNT[n], bgcnt(prio=prio, char=char, color256=color256, screen=screen, size=size))


def default_tiles(scene):
    """4bpp glyph tiles 1..48 in char block 0, a solid tile per color at
    64..78, 8bpp glyph tiles 1..32 in char block 1, tile 0 empty."""
    for k in range(1, 49):
        scene.tile4(0, k, glyph4(k))
    for c in range(1, 16):
        scene.tile4(0, 63 + c, solid4(c))
    for k in range(1, 33):
        scene.tile8(0x4000, k, glyph8(k))


def scene_bg_text_4bpp():
    """Mode 0 text BGs with 16-color tiles: the four screen sizes, scrolling
    across screen-block boundaries and wraparound, H/V flip, palette banks,
    and priority between BGs, including equal priorities.
    GBATEK: "LCD I/O Display Control", "LCD I/O BG Control", "LCD I/O BG
    Scrolling", "LCD VRAM BG Screen Data Format (BG Map)", "LCD VRAM Character
    Data", "LCD Color Palettes"."""
    s = Scene('bg_text_4bpp', scene_bg_text_4bpp.__doc__)
    s.bg_palettes()
    s.bg_color(0, rgb(3, 5, 8))
    default_tiles(s)
    text_layer(s, 0, 0, 16, None, prio=1,
               pattern=lambda x, y: (1 + (x + y) % 48, x % 2, y % 3 == 0, (x + 2 * y) % 16) if (x // 3 + y // 2) % 3 == 0 else None)
    text_layer(s, 1, 1, 18, None, prio=1,
               pattern=lambda x, y: (1 + (3 * x + y) % 48, y % 2, x % 2, (x // 32) * 8 + y % 8) if (x + y) % 4 else None)
    text_layer(s, 2, 2, 20, None, prio=0,
               pattern=lambda x, y: (64 + (y // 32) * 7 + x % 7, False, False, 3) if x % 8 == 5 and (y // 4) % 2 else None)
    text_layer(s, 3, 3, 24, None, prio=2,
               pattern=lambda x, y: (1 + (x * 5 + y * 3) % 48, (x + y) % 2, y % 2, (x // 32) + 2 * (y // 32) + 4))
    for n, (h, v) in enumerate(((13, 7), (300, 20), (5, 400), (500, 470))):
        s.reg(BGHOFS[n], h)
        s.reg(BGVOFS[n], v)
    s.dispcnt = 0x0F00
    return s


