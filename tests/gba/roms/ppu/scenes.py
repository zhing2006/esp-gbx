def bitmap_image(s, mode, frame):
    base = frame * 0xA000
    if mode == 3:
        for y in range(160):
            for x in range(240):
                struct.pack_into('<H', s.vram, (y * 240 + x) * 2, rgb(x // 8, y // 5, (x + y) // 12))
    elif mode == 4:
        for y in range(160):
            for x in range(240):
                s.vram[base + y * 240 + x] = 0 if (x // 16 + y // 16) % 4 == 0 else (x * 3 + y + frame * 77) & 0xFF
    else:
        for y in range(128):
            for x in range(160):
                struct.pack_into('<H', s.vram, base + (y * 160 + x) * 2,
                                 rgb(x // 5 + frame * 9, y // 4, 31 - x // 5) if frame else rgb(31, 0, 0))


def bitmap_objs(s):
    """OBJ tiles in the upper 16K of OBJ VRAM, used in bitmap modes."""
    s.obj_palettes()
    for k in range(16):
        s.tile4(0x10000, 512 + k, glyph4(k + 3))
        s.tile4(0x10000, k, glyph4(k + 20))
    s.obj(0, 20, 30, 0, 1, 512, prio=0, pal=1)
    s.obj(1, 60, 30, 0, 1, 0, prio=0, pal=2)  # tiles 0-511: not displayed
    s.obj(2, 200, 120, 0, 1, 516, prio=3, pal=3)


def scene_bitmap_mode3():
    """Mode 3 bitmap on BG2, zoomed by the affine parameters so that part of
    the screen lies outside the bitmap and shows the backdrop, with OBJs
    above and below. In bitmap modes only OBJ tiles 512-1023 are displayed.
    GBATEK: "LCD VRAM Bitmap BG Modes", "LCD I/O BG Rotation/Scaling", "LCD
    OBJ - OAM Attributes" (OBJ Tile Number)."""
    s = Scene('bitmap_mode3', scene_bitmap_mode3.__doc__)
    s.bg_color(0, rgb(20, 0, 20))
    bitmap_image(s, 3, 0)
    bitmap_objs(s)
    s.reg(BGCNT[2], bgcnt(prio=1))
    affine(s, 2, 0x0080, 0, 0, 0x00C0, 0x4000, 0x2000)
    s.dispcnt = 0x1403 | 0x40
    return s


