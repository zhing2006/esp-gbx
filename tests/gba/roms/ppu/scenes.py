def raster_scene(name, doc, mode):
    """Shared content of the raster scenes; mode selects H-Blank DMA or the
    H-Blank IRQ handler for all per-line writes."""
    s = Scene(name, doc)
    s.bg_palette256()
    s.obj_palettes()
    s.quantize_bank(0, LEVELS_8)
    s.bg_color(0, rgb(2, 2, 10))
    default_tiles(s)
    text_layer(s, 0, 0, 16, None, prio=0, pattern=lambda x, y: (1 + (x + y) % 48, False, False, 0) if y % 3 else None)
    text_layer(s, 1, 0, 17, None, prio=2, pattern=lambda x, y: (64 + (x // 3 + y // 3) % 15, False, False, 0))
    affine_map(s, 24, 32)
    s.reg(BGCNT[2], bgcnt(prio=1, char=1, color256=True, screen=24, wrap=True, size=1))
    # BG0 horizontal wave.
    wave = [0, 1, 3, 4, 5, 5, 4, 3, 1, 0, -1, -3, -4, -5, -5, -4, -3, -1]
    s.per_line(BGHOFS[0], 2, lambda line: [wave[line % 18] & 0x1FF], mode=mode, channel=0)
    # BG2 perspective-like floor: per-line PA, PC and reference point with
    # PB = PD = 0 (GBATEK "LCD I/O BG Rotation/Scaling").
    def floor(line):
        scale = 0x40 + line * 2
        pa = scale
        pc = -(line // 4)
        x = (0x2000 - 120 * scale) & 0xFFFFFFFF
        y = ((line * 3) << 8) & 0xFFFFFFFF
        return [pa & 0xFFFF, pc & 0xFFFF, x, y]
    s.reg(BGPB[2], 0)
    s.reg(BGPD[2], 0)
    s.per_line(BGPA[2], 4, floor, mode=mode, channel=1)
    # Blend BG0 over BG1 with EVA rising down the screen.
    s.reg(BLDCNT, 0x01 | (1 << 6) | (0x02 << 8))
    s.per_line(BLDALPHA, 2, lambda line: [2 * min(8, line // 20) | ((16 - 2 * min(8, line // 20)) << 8)],
               mode=mode, channel=2)
    # Window 0 as a diamond.
    def diamond(line):
        half = max(0, 70 - abs(line - 80))
        return [((120 - half) << 8) | (120 + half)]
    s.reg(WIN0V, (0 << 8) | 160)
    s.reg(WININ, 0x3F)
    s.reg(WINOUT, 0x02 | 0x04)
    s.per_line(WIN0H, 2, diamond, mode=mode, channel=3)
    s.dispcnt = 0x0701 | 0x2000
    return s


