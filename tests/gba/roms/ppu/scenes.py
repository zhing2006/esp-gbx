def scene_obj_cycles(hblank_free):
    """OBJ rendering cycles per line: OBJs whose cycles fit well within the
    per-line budget are drawn, OBJs that start well after the budget is used
    up are not. GBATEK gives the budget (1210 cycles, 954 with H-Blank
    Interval Free) and the cost (n cycles for a normal OBJ n pixels wide,
    10 + 2n for an affine OBJ n pixels wide including the double-size area),
    but not what happens to the OBJ at which the budget runs out, so the
    OBJs around that point are hidden under earlier OBJs.
    GBATEK: "LCD OBJ - Overview" (Maximum Number of Sprites per Line), "LCD
    I/O Display Control" (H-Blank Interval Free)."""
    name = 'obj_cycles_hblank_free' if hblank_free else 'obj_cycles'
    s = Scene(name, scene_obj_cycles.__doc__)
    s.bg_color(0, rgb(8, 0, 8))
    s.obj_palettes()
    for k in range(1024):
        s.tile4(0x10000, k, glyph4(k % 47 + 1))
    s.obj_affine(0, 0x100, 0, 0, 0x100)
    # Lines 0-31: 64x32 normal OBJs, 64 cycles each. OBJ k at x = 236 - 4k
    # shows 4 columns of its own. With 1210 cycles, OBJs 0-17 (1152 cycles)
    # are drawn; 18 and 19 sit under OBJ 15; 20-23 start at 1280 cycles or
    # later. With 954: 0-13 (896) drawn, 14 and 15 hidden, 16-19 from 1024 on.
    drawn, hidden, dropped = (18, 2, 4) if not hblank_free else (14, 2, 4)
    i = 0
    for k in range(drawn):
        s.obj(i, 236 - 4 * k, 0, 1, 3, (i * 8) % 1024, pal=i % 16)
        i += 1
    for k in range(hidden):
        s.obj(i, 236 - 4 * (drawn - 3), 0, 1, 3, (i * 8) % 1024, pal=i % 16)
        i += 1
    for k in range(dropped):
        s.obj(i, k * 40, 0, 1, 3, (i * 8) % 1024, pal=i % 16)
        i += 1
    # Lines 32-159: 64x64 affine OBJs in the 128x128 double-size area, 266
    # cycles each, with the picture in the middle 64x64 (lines 64-127).
    # With 1210 cycles: 4 drawn (1064), 1 hidden, the next starts at 1330.
    # With 954: 3 drawn (798), 1 hidden, the next starts at 1064.
    drawn, hidden, dropped = (4, 1, 2) if not hblank_free else (3, 1, 2)
    for k in range(drawn):
        s.obj(i, (48 * k - 32) & 0x1FF, 32, 0, 3, (i * 8) % 1024, affine=0, double=True, pal=i % 16)
        i += 1
    for k in range(hidden):
        s.obj(i, (48 - 32) & 0x1FF, 32, 0, 3, (i * 8) % 1024, affine=0, double=True, pal=i % 16)
        i += 1
    for k in range(dropped):
        s.obj(i, (176 + 32 * k - 32) & 0x1FF, 32, 0, 3, (i * 8) % 1024, affine=0, double=True, pal=i % 16)
        i += 1
    s.dispcnt = 0x1040 | (0x20 if hblank_free else 0)
    return s


def scene_window():
    """Window 0 and 1 overlapping, the OBJ window, and outside of windows,
    each with its own layer set and color special effect enable, under a
    brightness increase.
    GBATEK: "LCD I/O Window Feature", "LCD I/O Color Special Effects"."""
    s = Scene('window', scene_window.__doc__)
    s.bg_palettes()
    s.obj_palettes()
    s.bg_color(0, rgb(0, 6, 12))
    default_tiles(s)
    for k in range(64):
        s.tile4(0x10000, k, glyph4(k % 47 + 1))
    text_layer(s, 0, 0, 16, None, prio=0, pattern=lambda x, y: (1 + (x + y) % 48, False, False, 1))
    text_layer(s, 1, 0, 17, None, prio=1, pattern=lambda x, y: (64 + (x // 2 + y) % 15, False, False, 2))
    text_layer(s, 2, 0, 18, None, prio=2, pattern=lambda x, y: (1 + (x * 3) % 48, True, True, 3) if y % 2 else None)
    s.reg(WIN0H, (30 << 8) | 130)
    s.reg(WIN0V, (20 << 8) | 100)
    s.reg(WIN1H, (90 << 8) | 210)
    s.reg(WIN1V, (60 << 8) | 150)
    s.reg(WININ, 0x01 | 0x20 | (0x16 << 8))         # WIN0: BG0 + effect; WIN1: BG1, BG2, OBJ
    s.reg(WINOUT, 0x06 | (0x31 << 8))                # outside: BG1, BG2; OBJ window: BG0, OBJ, effect
    s.reg(BLDCNT, 0x0F | (2 << 6))
    s.reg(BLDY, 8)
    for bank in (1, 2, 3):
        s.quantize_bank(bank, LEVELS_UP)
    # OBJ window shapes and visible OBJs
    for k in range(4):
        s.obj(k, 150 + (k % 2) * 40, 8 + (k // 2) * 40, 0, 2, 4 * k, mode=2)
    s.obj(4, 40, 110, 0, 2, 16, pal=5)
    s.obj(5, 100, 70, 0, 2, 20, pal=6)
    s.dispcnt = 0x1700 | 0xE000 | 0x40
    return s


