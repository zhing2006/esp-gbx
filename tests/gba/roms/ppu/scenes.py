def affine_map(s, screen, size_tiles, offset=1, count=32):
    for ty in range(size_tiles):
        for tx in range(size_tiles):
            s.affine_entry(screen, size_tiles, tx, ty, offset + (tx * 3 + ty * 5) % count if (tx + ty) % 5 else 0)


def scene_bg_affine_mode1():
    """Mode 1: two text BGs under a rotated and scaled affine BG2 that wraps
    around (display area overflow on).
    GBATEK: "LCD I/O Display Control", "LCD I/O BG Control", "LCD I/O BG
    Rotation/Scaling", "LCD VRAM BG Screen Data Format (BG Map)"."""
