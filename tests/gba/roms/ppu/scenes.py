def obj_tiles(s, color256):
    """OBJ tiles: 4bpp glyphs at 0..1023 or 8bpp glyphs at even numbers."""
    if color256:
        for k in range(512):
            s.obj_tile8(2 * k, glyph8(k % 31 + 1))
    else:
        for k in range(1024):
            s.tile4(0x10000, k, glyph4(k % 47 + 1))


def obj_grid(s, one_dim):
    """All 12 shapes and sizes in 4bpp with flips and palette banks, a few in
    8bpp, and OBJs that wrap around the right and bottom edges. In 2D mapping
    no OBJ runs past the right edge of the 32x32-tile matrix, which GBATEK
    "LCD OBJ - VRAM Character (Tile) Mapping" does not cover."""
    i = 0
    x, y = 0, 0
    for shape in range(3):
        for size in range(4):
            w, h = OBJ_SIZES[shape][size]
            if x + w > 236:
                x, y = 0, y + 36
            tile = (i * 37) % 900
